using System.Collections.Generic;
using UnityEngine;

public enum SkinPattern { Solid, Stripes, Dots, Checker, Gradient, Zigzag }
/// Body silhouette of the round spider. Skins only differ by colour, spikes and this shape (no props).
public enum SkinShape { Round, Chubby, Tall, Flat, Pear }
public enum SkinUnlock { Free, Coins, Ads, BestScore, Runs }

[System.Serializable]
public class SkinDef
{
    public string name; public Color body; public Color accent; public SkinPattern pattern;
    public float emission; public Color trail; public SkinShape shape; public int spikes; public float spikeLength;
    public SkinUnlock unlock; public int amount;
    public Color eye; public float eyeGlow, metallic, gloss;
    public SkinDef(string n, string b, string a, SkinPattern p, float e, string t, SkinShape s, int sp, float spLen, SkinUnlock u, int amt, string eyeHex = "#141216", float eyeGlow = 0f, float metallic = 0f, float gloss = 0.35f)
    { name = n; body = C(b); accent = C(a); pattern = p; emission = e; trail = C(t); shape = s; spikes = sp; spikeLength = spLen; unlock = u; amount = amt; eye = C(eyeHex); this.eyeGlow = eyeGlow; this.metallic = metallic; this.gloss = gloss; }
    static Color C(string hex) { ColorUtility.TryParseHtmlString(hex, out var c); return c; }

    public Vector3 BodyScale => shape switch
    {
        SkinShape.Chubby => new Vector3(1.08f, 0.82f, 0.98f),
        SkinShape.Tall => new Vector3(0.90f, 0.95f, 0.95f),
        SkinShape.Flat => new Vector3(1.08f, 0.68f, 0.96f),
        SkinShape.Pear => new Vector3(0.96f, 0.85f, 1.05f),
        _ => new Vector3(1.0f, 0.82f, 0.98f)
    };

    public string UnlockText => unlock switch
    {
        SkinUnlock.Coins => amount + "",
        SkinUnlock.Ads => "Watch " + amount + " ads",
        SkinUnlock.BestScore => "Climb " + amount + "M",
        SkinUnlock.Runs => "Play " + amount + " runs",
        _ => "Free"
    };
}

