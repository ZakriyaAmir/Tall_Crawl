    public static bool CanAutoUnlock(int i)
    {
        var s = All[i];
        return (s.unlock == SkinUnlock.BestScore && TCSave.Best >= s.amount)
            || (s.unlock == SkinUnlock.Runs && TCSave.Runs >= s.amount)
            || (s.unlock == SkinUnlock.Ads && TCSave.SkinAdsWatched(i) >= s.amount);
    }
    public static void CheckAchievements()
    {
        for (int i = 0; i < All.Length; i++) if (!TCSave.SkinOwned(i) && CanAutoUnlock(i)) TCSave.UnlockSkin(i);
    }

    /// Applies skin i to a spider (the "newSpider" object or the menu preview copy):
    /// hides the old realistic mesh and (re)builds the round cute spider in that skin.
    public static void Apply(GameObject spider, int i)
    {
        i = Mathf.Clamp(i, 0, All.Length - 1);
        var def = All[i];
        TCCuteSpider.Build(spider, def, i);
        // Trail (colour only)
        var tr = spider.GetComponent<TrailRenderer>();
        if (def.trail.a > 0.01f)
        {
            if (!tr) tr = spider.AddComponent<TrailRenderer>();
            tr.sharedMaterial = Resources.Load<Material>("Skins/Trail");
            tr.time = 0.35f; tr.minVertexDistance = 0.05f;
            tr.widthCurve = new AnimationCurve(new Keyframe(0, 0.12f), new Keyframe(1, 0));
            var g = new Gradient();
            g.SetKeys(new[] { new GradientColorKey(def.trail, 0), new GradientColorKey(def.accent, 1) },
                      new[] { new GradientAlphaKey(0.75f, 0), new GradientAlphaKey(0, 1) });
            tr.colorGradient = g; tr.enabled = true;
            tr.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        }
        // Golden Gleam Particles (Skin 19: Golden Spider)
        var oldGoldFx = spider.transform.Find("GoldGleamFx");
        if (i == 19)
        {
            if (!oldGoldFx)
            {
                var fxObj = new GameObject("GoldGleamFx");
                fxObj.transform.SetParent(spider.transform, false);
                fxObj.transform.localPosition = new Vector3(0, 0.2f, 0);

                var ps = fxObj.AddComponent<ParticleSystem>();
                var main = ps.main;
                main.loop = true;
                main.startLifetime = 1.0f;
                main.startSpeed = 0.25f;
                main.startSize = new ParticleSystem.MinMaxCurve(0.04f, 0.09f);
                main.startColor = new ParticleSystem.MinMaxGradient(new Color(1f, 0.88f, 0.35f, 1f), new Color(1f, 1f, 0.85f, 1f));
                main.simulationSpace = ParticleSystemSimulationSpace.World;
                main.maxParticles = 35;

                var emission = ps.emission;
                emission.rateOverTime = 16f;

                var shape = ps.shape;
                shape.shapeType = ParticleSystemShapeType.Sphere;
                shape.radius = 0.45f;

                var colOverLifetime = ps.colorOverLifetime;
                colOverLifetime.enabled = true;
                var grad = new Gradient();
                grad.SetKeys(
                    new[] { new GradientColorKey(new Color(1f, 0.85f, 0.2f), 0f), new GradientColorKey(new Color(1f, 1f, 0.9f), 0.5f), new GradientColorKey(new Color(1f, 0.75f, 0.1f), 1f) },
                    new[] { new GradientAlphaKey(0f, 0f), new GradientAlphaKey(1f, 0.3f), new GradientAlphaKey(0f, 1f) }
                );
                colOverLifetime.color = grad;

                var sizeOverLifetime = ps.sizeOverLifetime;
                sizeOverLifetime.enabled = true;
                var sizeCurve = new AnimationCurve(new Keyframe(0f, 0.2f), new Keyframe(0.5f, 1f), new Keyframe(1f, 0f));
                sizeOverLifetime.size = new ParticleSystem.MinMaxCurve(1f, sizeCurve);

                var psRenderer = fxObj.GetComponent<ParticleSystemRenderer>();
                psRenderer.sharedMaterial = Resources.Load<Material>("Skins/Trail") ?? new Material(Shader.Find("Sprites/Default"));
            }
        }
        else if (oldGoldFx)
        {
            Object.Destroy(oldGoldFx.gameObject);
        }
    }

    public static Transform FindDeep(Transform t, string n)
    {
        if (t.name == n) return t;
        foreach (Transform c in t) { var r = FindDeep(c, n); if (r) return r; }
        return null;
    }
