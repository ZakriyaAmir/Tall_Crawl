    public static bool CanAutoUnlock(int i)
    {
        var s = All[i];
        return (s.unlock == SkinUnlock.BestScore && TCSave.Best >= s.amount)
            || (s.unlock == SkinUnlock.Runs && TCSave.Runs >= s.amount)
            || (s.unlock == SkinUnlock.Ads && TCSave.SkinAdsWatched(i) >= s.amount);
    }
    public static void CheckAchievements()
    {
        for (int i = 0; i < All.Length; i++) if (!TCSave.SkinOwned(i) && CanAutoUnlock(i)) TCSave.UnlockSkin(i);
    }

    /// Applies skin i to a spider (the "newSpider" object or the menu preview copy).
    public static void Apply(GameObject spider, int i)
    {
        var def = All[Mathf.Clamp(i, 0, All.Length - 1)];
        var smr = spider.GetComponentInChildren<SkinnedMeshRenderer>(true);
        var mat = Resources.Load<Material>("Skins/Skin_" + i);
        if (smr && mat)
        {
            var mats = smr.sharedMaterials;
            for (int m = 0; m < mats.Length; m++) mats[m] = mat;
            smr.sharedMaterials = mats;
        }
        // Hat
        var old = spider.transform.Find("__hat");
        if (old) Object.Destroy(old.gameObject);
        var head = FindDeep(spider.transform, "Spider_Head");
        if (def.hat != SkinHat.None && head && smr)
        {
            var hatMat = Resources.Load<Material>("Skins/Hat_" + i);
            var hat = BuildHat(def.hat, hatMat);
            hat.name = "__hat";
            float size = smr.bounds.size.magnitude * 0.16f;
            hat.transform.SetParent(spider.transform, false);
            var follow = hat.AddComponent<TCHatFollow>();
            follow.head = head; follow.body = spider.transform; follow.size = size;
        }
        // Trail
        var tr = spider.GetComponent<TrailRenderer>();
        if (def.trail.a > 0.01f)
        {
            if (!tr) tr = spider.AddComponent<TrailRenderer>();
            tr.sharedMaterial = Resources.Load<Material>("Skins/Trail");
            tr.time = 0.35f; tr.minVertexDistance = 0.05f;
            tr.widthCurve = new AnimationCurve(new Keyframe(0, 0.12f), new Keyframe(1, 0));
            var g = new Gradient();
            g.SetKeys(new[] { new GradientColorKey(def.trail, 0), new GradientColorKey(def.accent, 1) },
                      new[] { new GradientAlphaKey(0.75f, 0), new GradientAlphaKey(0, 1) });
            tr.colorGradient = g; tr.enabled = true;
            tr.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        }
        else if (tr) tr.enabled = false;
    }

    static GameObject Prim(PrimitiveType t, Transform p, Vector3 pos, Vector3 scale, Material m, Vector3 euler = default)
    {
        var g = GameObject.CreatePrimitive(t);
        Object.Destroy(g.GetComponent<Collider>());
        g.transform.SetParent(p, false); g.transform.localPosition = pos; g.transform.localScale = scale; g.transform.localEulerAngles = euler;
        var r = g.GetComponent<MeshRenderer>(); r.sharedMaterial = m; r.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        return g;
    }

    // Hats are unit-sized, "up" = +Y; TCHatFollow scales/orients them each frame.
    static GameObject BuildHat(SkinHat h, Material m)
    {
        var root = new GameObject("hat"); var t = root.transform;
        switch (h)
        {
            case SkinHat.TopHat:
                Prim(PrimitiveType.Cylinder, t, Vector3.zero, new Vector3(1.4f, 0.05f, 1.4f), m);
                Prim(PrimitiveType.Cylinder, t, new Vector3(0, 0.5f, 0), new Vector3(0.85f, 0.5f, 0.85f), m); break;
            case SkinHat.Crown:
                Prim(PrimitiveType.Cylinder, t, new Vector3(0, 0.15f, 0), new Vector3(1f, 0.15f, 1f), m);
                for (int k = 0; k < 5; k++) { float a = k * 72 * Mathf.Deg2Rad; Prim(PrimitiveType.Sphere, t, new Vector3(Mathf.Cos(a) * 0.45f, 0.4f, Mathf.Sin(a) * 0.45f), Vector3.one * 0.25f, m); } break;
            case SkinHat.Cap:
                Prim(PrimitiveType.Sphere, t, new Vector3(0, 0.05f, 0), new Vector3(1.1f, 0.6f, 1.1f), m);
                Prim(PrimitiveType.Cube, t, new Vector3(0, 0.02f, 0.6f), new Vector3(0.8f, 0.05f, 0.6f), m); break;
            case SkinHat.Halo:
                for (int k = 0; k < 10; k++) { float a = k * 36 * Mathf.Deg2Rad; Prim(PrimitiveType.Sphere, t, new Vector3(Mathf.Cos(a) * 0.6f, 0.8f, Mathf.Sin(a) * 0.6f), Vector3.one * 0.2f, m); } break;
            case SkinHat.Horns:
                Prim(PrimitiveType.Capsule, t, new Vector3(-0.4f, 0.3f, 0), new Vector3(0.22f, 0.4f, 0.22f), m, new Vector3(0, 0, 25));
                Prim(PrimitiveType.Capsule, t, new Vector3(0.4f, 0.3f, 0), new Vector3(0.22f, 0.4f, 0.22f), m, new Vector3(0, 0, -25)); break;
            case SkinHat.Antenna:
                Prim(PrimitiveType.Cylinder, t, new Vector3(-0.3f, 0.4f, 0), new Vector3(0.06f, 0.4f, 0.06f), m, new Vector3(0, 0, 15));
                Prim(PrimitiveType.Cylinder, t, new Vector3(0.3f, 0.4f, 0), new Vector3(0.06f, 0.4f, 0.06f), m, new Vector3(0, 0, -15));
                Prim(PrimitiveType.Sphere, t, new Vector3(-0.42f, 0.82f, 0), Vector3.one * 0.22f, m);
                Prim(PrimitiveType.Sphere, t, new Vector3(0.42f, 0.82f, 0), Vector3.one * 0.22f, m); break;
            case SkinHat.Bow:
                Prim(PrimitiveType.Sphere, t, new Vector3(-0.3f, 0.2f, 0), new Vector3(0.55f, 0.35f, 0.25f), m);
                Prim(PrimitiveType.Sphere, t, new Vector3(0.3f, 0.2f, 0), new Vector3(0.55f, 0.35f, 0.25f), m);
                Prim(PrimitiveType.Sphere, t, new Vector3(0, 0.2f, 0), Vector3.one * 0.22f, m); break;
        }
        return root;
    }

    public static Transform FindDeep(Transform t, string n)
    {
        if (t.name == n) return t;
        foreach (Transform c in t) { var r = FindDeep(c, n); if (r) return r; }
        return null;
    }
}

/// Keeps a hat on the spider head (bone animated), pointing away from the trunk (spider's back).
public class TCHatFollow : MonoBehaviour
{
    public Transform head, body; public float size = 0.1f;
    public static Vector3 UpOverride; // set for the menu preview
    void LateUpdate()
    {
        if (!head) return;
        Vector3 p = head.position;
        Vector3 up = UpOverride != Vector3.zero ? UpOverride : new Vector3(p.x, 0, p.z).normalized;
        if (up.sqrMagnitude < 0.01f) up = Vector3.up;
        transform.position = p + up * size * 0.55f;
        transform.rotation = Quaternion.LookRotation(Vector3.up, up);
        transform.localScale = Vector3.one * size / Mathf.Max(0.0001f, body.lossyScale.x);
    }
}
